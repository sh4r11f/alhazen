#!/usr/bin/env node
// Build the Alhazen Experiment Platform web app from platform-web/src.
//
//   node platform-web/build.mjs                 write src/alhazen/experiment_platform/web/
//   node platform-web/build.mjs --mana out.jsx  also write the Mana user_div code to out.jsx
//   node platform-web/build.mjs --check         rebuild into a temporary directory; exit 1 if the
//                                               committed web/ files differ (the CI gate)
//
// Dependencies come from package-lock.json, installed outside the repository:
//   npm ci --prefix /tmp/apw-node --cache /tmp/npm-cache   (with package.json and the lock copied there)
//   ALHAZEN_PLATFORM_NODE_MODULES=/tmp/apw-node/node_modules node platform-web/build.mjs
// Without the variable, platform-web/node_modules is used.
//
// Sources are fragments concatenated in a fixed order into one scope, because the Mana export must be
// a single user_div with no import statements (Mana injects React, ReactMarkdown, remarkGfm, FS, ...).
// The standalone build splices the same fragments plus the HTTP host into entry_standalone.jsx and
// bundles React from the lockfile; nothing is fetched from a CDN at run time.
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import vm from 'node:vm';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, '..');
const SRC = path.join(HERE, 'src');
const OUT = path.join(REPO, 'src', 'alhazen', 'experiment_platform', 'web');
const FONT_DIR = path.join(REPO, 'src', 'alhazen', 'cli', 'assets', 'fonts');
// Manrope as vendored with the alhazen dashboard; identical to the hub copy at a8de721.
const FONT_SHA256 = '1c84dc33ba72aa5b6fd9130a59846c79d6cb4bf13aeb3cc2c3aaa3d928aa4752';
const OFL_SHA256 = '58172e0c0fac2cda8a37b348164bb55e44b0e69051e557e92b1d3f6910141f7b';

export const SHARED = ['00_guide_css.js', '10_constants.js', '20_styles.js', '30_hub_docs.js', '40_reader.jsx',
  '50_logos.jsx', '60_helpers.js', '70_app.jsx'];
const MARKER = '/* @@PLATFORM_SOURCES@@ */';
const OUTPUTS = ['index.html', 'platform.js', 'platform.css', 'assets.json', 'fonts/Manrope-latin.woff2', 'fonts/OFL.txt',
  'THIRD_PARTY_LICENSES.txt'];

function fail(message) {
  process.stderr.write('build.mjs: ' + message + '\n');
  process.exit(2);
}

function parseArgs(argv) {
  const args = { mana: null, check: false };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--check') args.check = true;
    else if (argv[i] === '--mana') { args.mana = argv[++i]; if (!args.mana) fail('--mana needs an output path'); }
    else fail('unknown argument ' + argv[i]);
  }
  return args;
}

function nodeModules() {
  const dir = process.env.ALHAZEN_PLATFORM_NODE_MODULES || path.join(HERE, 'node_modules');
  if (!fs.existsSync(path.join(dir, 'esbuild'))) {
    fail('no dependencies at ' + dir + '. Install them outside the repository (see the header of this file).');
  }
  return dir;
}

const read = (name) => fs.readFileSync(path.join(SRC, name), 'utf8');
const sha256 = (buf) => createHash('sha256').update(buf).digest('hex');

function joinFragments(names) {
  return names.map((name) => {
    const text = read(name);
    if (/^\s*(import|export)\s/m.test(text)) fail(name + ' has an import or export statement; fragments share one scope');
    return '// ---- ' + name + '\n' + text.replace(/\s*$/, '\n');
  }).join('\n');
}

export function manaSource() {
  return '// Alhazen Experiment Platform: Mana user_div. Generated by platform-web/build.mjs from\n'
    + '// platform-web/src in the alhazen repository; edit the source there, not this export.\n\n'
    + joinFragments([...SHARED, 'host_mana.jsx']);
}

function assets() {
  const svg = (name) => fs.readFileSync(path.join(HERE, 'assets', name + '.svg'), 'utf8');
  return { hero: svg('hero'), penrose: svg('penrose') };
}

function standaloneSource(assetMap) {
  const entry = read('entry_standalone.jsx');
  if (!entry.includes(MARKER)) fail('entry_standalone.jsx lost its ' + MARKER + ' marker');
  const body = joinFragments([...SHARED, 'host_http.jsx'])
    + '\n// ---- assets (platform-web/assets)\nconst PLATFORM_ASSETS = ' + JSON.stringify(assetMap) + ';\n';
  return entry.replace(MARKER, body);
}

function stylesheet() {
  // The CSS constants are plain strings; evaluate those three fragments alone to get them.
  const code = ['00_guide_css.js', '20_styles.js', 'standalone_css.js'].map(read).join('\n')
    + '\n;({ GUIDE_CSS, CSS, STANDALONE_CSS })';
  const { GUIDE_CSS, CSS, STANDALONE_CSS } = vm.runInNewContext(code, {}, { timeout: 2000 });
  return '/* Alhazen Experiment Platform. Generated by platform-web/build.mjs. */\n' + CSS + GUIDE_CSS + STANDALONE_CSS;
}

const INDEX_HTML = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<meta name="referrer" content="no-referrer">
<title>Alhazen Experiment Platform</title>
<link rel="stylesheet" href="assets/platform.css">
<script defer src="assets/platform.js"></script>
</head>
<body>
<div id="root"></div>
<noscript>The Alhazen Experiment Platform needs JavaScript.</noscript>
</body>
</html>
`;

function licenseText(dir) {
  for (const name of ['LICENSE', 'LICENSE.md', 'license', 'license.md', 'LICENSE.txt']) {
    const p = path.join(dir, name);
    if (fs.existsSync(p)) return fs.readFileSync(p, 'utf8').trim();
  }
  return null;
}

function thirdPartyLicenses(metafile, modulesDir) {
  const packages = new Map();
  for (const input of Object.keys(metafile.inputs)) {
    const abs = path.resolve(REPO, input);
    const marker = path.sep + 'node_modules' + path.sep;
    const at = abs.lastIndexOf(marker);
    if (at < 0) continue; // our own source (the stdin entry)
    const parts = abs.slice(at + marker.length).split(path.sep);
    const name = parts[0].startsWith('@') ? parts[0] + '/' + parts[1] : parts[0];
    const dir = abs.slice(0, at + marker.length) + name;
    if (packages.has(name)) continue;
    const meta = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
    const text = licenseText(dir);
    if (!text) fail('no licence file in bundled package ' + name);
    packages.set(name, { version: meta.version, license: meta.license, text });
  }
  const lines = ['Third-party software in the Alhazen Experiment Platform web app',
    '(src/alhazen/experiment_platform/web/). Generated by platform-web/build.mjs from the bundled packages.', ''];
  lines.push('Manrope font (fonts/Manrope-latin.woff2): SIL Open Font License 1.1, see fonts/OFL.txt.', '');
  for (const name of [...packages.keys()].sort()) {
    const p = packages.get(name);
    lines.push('='.repeat(72), name + ' ' + p.version + ' (' + p.license + ')', '='.repeat(72), p.text, '');
  }
  return lines.join('\n');
}

async function buildInto(dir, modulesDir) {
  const require = createRequire(path.join(modulesDir, 'noop.js'));
  const esbuild = require('esbuild');
  const assetMap = assets();
  const result = await esbuild.build({
    stdin: { contents: standaloneSource(assetMap), loader: 'jsx', resolveDir: SRC, sourcefile: 'entry_standalone.jsx' },
    bundle: true, write: false, format: 'iife', platform: 'browser', target: ['es2020'], minify: true,
    legalComments: 'none', charset: 'utf8', metafile: true, logLevel: 'silent',
    define: { 'process.env.NODE_ENV': '"production"' }, nodePaths: [modulesDir], absWorkingDir: REPO,
  });
  const files = {
    'index.html': INDEX_HTML,
    'platform.js': '/* Alhazen Experiment Platform. Generated by platform-web/build.mjs; third-party notices in THIRD_PARTY_LICENSES.txt. */\n' + result.outputFiles[0].text,
    'platform.css': stylesheet(),
    'assets.json': JSON.stringify(assetMap, null, 1) + '\n',
    'THIRD_PARTY_LICENSES.txt': thirdPartyLicenses(result.metafile, modulesDir),
  };
  fs.mkdirSync(path.join(dir, 'fonts'), { recursive: true });
  for (const [name, text] of Object.entries(files)) fs.writeFileSync(path.join(dir, name), text);
  for (const [name, digest] of [['Manrope-latin.woff2', FONT_SHA256], ['OFL.txt', OFL_SHA256]]) {
    const buf = fs.readFileSync(path.join(FONT_DIR, name));
    if (sha256(buf) !== digest) fail('the vendored ' + name + ' changed (sha256 ' + sha256(buf) + ')');
    fs.writeFileSync(path.join(dir, 'fonts', name), buf);
  }
  // Parse-check what was written: the bundle with node --check, the CSS by esbuild.
  execFileSync(process.execPath, ['--check', path.join(dir, 'platform.js')], { stdio: 'pipe' });
  await esbuild.transform(files['platform.css'], { loader: 'css', logLevel: 'silent' });
  return esbuild;
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const modulesDir = nodeModules();
  if (args.check) {
    const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'alhazen-platform-web-'));
    try {
      await buildInto(tmp, modulesDir);
      const differ = OUTPUTS.filter((name) => {
        const committed = path.join(OUT, name);
        return !fs.existsSync(committed) || sha256(fs.readFileSync(committed)) !== sha256(fs.readFileSync(path.join(tmp, name)));
      });
      if (differ.length) {
        process.stderr.write('build.mjs --check: committed web assets are out of date: ' + differ.join(', ')
          + '\nRun node platform-web/build.mjs and commit the result.\n');
        process.exit(1);
      }
      process.stdout.write('build.mjs --check: web assets match platform-web/src (' + OUTPUTS.length + ' files).\n');
    } finally {
      fs.rmSync(tmp, { recursive: true, force: true });
    }
  } else {
    fs.mkdirSync(OUT, { recursive: true });
    await buildInto(OUT, modulesDir);
    process.stdout.write('build.mjs: wrote ' + OUTPUTS.length + ' files to ' + path.relative(REPO, OUT) + '\n');
  }
  if (args.mana) {
    const require = createRequire(path.join(modulesDir, 'noop.js'));
    const esbuild = require('esbuild');
    const code = manaSource();
    // Parse-check as Mana compiles it: JSX inside one function body.
    await esbuild.transform('function __manaUserDiv(){\n' + code + '\nreturn UserDiv;}', { loader: 'jsx', logLevel: 'silent' });
    fs.writeFileSync(args.mana, code);
    process.stdout.write('build.mjs: wrote the Mana user_div (' + code.length + ' characters) to ' + args.mana + '\n');
  }
}

main().catch((error) => { process.stderr.write('build.mjs: ' + (error.stack || error) + '\n'); process.exit(2); });
